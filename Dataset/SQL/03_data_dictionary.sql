-- Year-Month
-- Year and month combination used for monthly trend analysis.
-- Format: YYYY-MM

-- Order Month
-- Numeric month extracted from Order Date.
-- Values: 1-12

-- Order Quarter
-- Quarter extracted from Order Date.
-- Values: 1-4


/* ============================================================
   3. TRANSACTION / NUMERICAL COLUMNS
   ============================================================ */

-- Order ID
-- Unique identifier for the sales order.

-- Units Sold
-- Number of units sold in the transaction.

-- Unit Price
-- Selling price per unit.

-- Unit Cost
-- Cost incurred per unit.

-- Total Revenue
-- Total sales revenue generated by the transaction.
-- Business rule:
-- Units Sold × Unit Price

-- Total Cost
-- Total cost associated with the transaction.
-- Business rule:
-- Units Sold × Unit Cost

-- Total Profit
-- Profit generated by the transaction.
-- Business rule:
-- Total Revenue − Total Cost

-- Shipping Days
-- Number of days between Order Date and Ship Date.

-- Profit Margin %
-- Profit as a percentage of Total Revenue.
-- Business rule:
-- Total Profit / Total Revenue × 100


